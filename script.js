const write=(k,v)=>{try{localStorage.setItem(k,v)}catch(e){}};
let USED=new Set(); // answers already played (Set = instant lookups)
function load(){let s=null;try{s=JSON.parse(read(KEY))}catch(e){}
  if(!s||typeof s!=='object'||!Array.isArray(s.dist)||s.dist.length!==6)s=blank();
  s.played=+s.played||0;s.won=+s.won||0;
  let used,old=Array.isArray(s.used);
  if(old){used=s.used;delete s.used}                 // old save: used list lived inside the main save
  else used=(read(USED_KEY)||'').split(' ');
  USED=new Set(used.filter(w=>VALID.has(w)));        // drops blanks and words removed from the list
  if(old){write(KEY,JSON.stringify(s));write(USED_KEY,[...USED].join(' '))}
  return s}
function save(){write(KEY,JSON.stringify(S))}       // small: runs on every key press
function saveUsed(){write(USED_KEY,[...USED].join(' '))} // big: runs once per new game
let S=load(),busy=false,toastT;

function rnd(n){const a=new Uint32Array(1),lim=Math.floor(4294967296/n)*n;
  do{crypto.getRandomValues(a)}while(a[0]>=lim);return a[0]%n}
function newGame(){
  const last=S.cur&&S.cur.answer;
  let pool=WORDS.filter(w=>!USED.has(w));
  if(!pool.length){USED=new Set(last?[last]:[]);pool=WORDS.filter(w=>!USED.has(w))}
  const a=pool[rnd(pool.length)];
  USED.add(a);
  S.cur={answer:a,guesses:[],typed:'',status:'playing'};
  save();saveUsed();
}
function score(g,a){
  const r=Array(5).fill('no'),c={};
  for(let i=0;i<5;i++){if(g[i]===a[i])r[i]='ok';else c[a[i]]=(c[a[i]]||0)+1}
  for(let i=0;i<5;i++)if(r[i]!=='ok'&&c[g[i]]>0){r[i]='pr';c[g[i]]--}
  return r}


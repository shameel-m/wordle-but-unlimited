function press(k){
  const c=S.cur;
  if(busy||c.status!=='playing'||!ov.hidden)return;
  if(k==='ENTER')return submit();
  if(k==='BACK')c.typed=c.typed.slice(0,-1);
  else if(/^[a-z]$/.test(k)&&c.typed.length<5)c.typed+=k;
  else return;
  save();drawTyped();
}
function submit(){
  const c=S.cur,g=c.typed;
  if(g.length<5){shake();toast('Not enough letters');return}
  if(!VALID.has(g)){shake();toast('Not a word');return}
  const r=c.guesses.length,res=score(g,c.answer);
  c.guesses.push(g);c.typed='';
  const win=g===c.answer,lost=!win&&c.guesses.length===6;
  if(win||lost){c.status=win?'won':'lost';S.played++;if(win){S.won++;S.dist[r]++}}
  save();
  busy=true;
  [...rows[r].children].forEach((t,i)=>{
    t.style.animation=`flip .5s ${i*.3}s both`;
    setTimeout(()=>{t.classList.remove('fill','pop');t.classList.add(res[i])},i*300+250)});
  setTimeout(()=>{
    busy=false;keys();sync();
    if(win){rows[r].classList.add('win');toast(PRAISE[r],1800)}
    if(win||lost)setTimeout(openStats,win?1500:700);
  },1700);
}

function openStats(){
  const c=S.cur,done=c.status!=='playing',mx=Math.max(1,...S.dist);
  let h=`<h2>${c.status==='won'?(PRAISE[c.guesses.length-1]||'You got it!'):c.status==='lost'?'Failed to solve':'Statistics'}</h2>`;
  if(c.status==='won')h+=`<p>Solved on try <b>${c.guesses.length}</b> of 6</p>`;
  if(c.status==='lost')h+=`<p>The word was <b>${c.answer.toUpperCase()}</b></p><p>Better luck next time!</p>`;
  h+=`<div class="stats"><div><b>${S.played}</b><span>Games played</span></div><div><b>${S.won}</b><span>Games won</span></div></div><h3>${c.status==='lost'?'Your wins so far':'Solved on try'}</h3>`;
  S.dist.forEach((n,i)=>{h+=`<div class="bar"><i>${i+1}</i><div><span class="${c.status==='won'&&c.guesses.length===i+1?'cur':''}" style="width:${Math.max(8,n/mx*100)}%">${n}</span></div></div>`});
  if(done)h+='<button class="btn" id="go">Next word</button>';
  mc.innerHTML=h;ov.hidden=false;
  const go=$('#go');if(go){go.onclick=next;go.focus()}
}
